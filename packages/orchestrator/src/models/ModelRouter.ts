export interface FileEditDirective {
  filePath: string;
  symbolOrLines?: string;
  changeSpec: string;
}

/**
 * Parses FileEditDirective[] from JSON code block, raw JSON array, or structured Markdown bullets.
 */
export function parseFileEditDirectives(text: string): FileEditDirective[] {
  if (!text) return [];

  // 1. Try markdown JSON code block
  const jsonBlockRegex = /```(?:json)?\s*(\[\s*\{[\s\S]*?\}\s*\])\s*```/i;
  const match = text.match(jsonBlockRegex);
  if (match) {
    try {
      const parsed = JSON.parse(match[1]);
      if (Array.isArray(parsed)) {
        return parsed.filter(
          (item): item is FileEditDirective =>
            Boolean(item && typeof item.filePath === 'string' && typeof item.changeSpec === 'string')
        );
      }
    } catch {
      // Fall through
    }
  }

  // 2. Try raw JSON array
  const rawJsonMatch = text.match(/\[\s*\{[\s\S]*?"filePath"[\s\S]*?\}\s*\]/);
  if (rawJsonMatch) {
    try {
      const parsed = JSON.parse(rawJsonMatch[0]);
      if (Array.isArray(parsed)) {
        return parsed.filter(
          (item): item is FileEditDirective =>
            Boolean(item && typeof item.filePath === 'string' && typeof item.changeSpec === 'string')
        );
      }
    } catch {
      // Fall through
    }
  }

  // 3. Try structured markdown bullets:
  // e.g. - filePath: `src/foo.ts` | symbolOrLines: `foo` | changeSpec: update bar
  // or   - file: src/foo.ts (lines: 10-25) -> changeSpec: add validation
  const lines = text.split(/\r?\n/);
  const directives: FileEditDirective[] = [];
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed.startsWith('-') && !trimmed.startsWith('*')) continue;
    const bullet = trimmed.replace(/^[-*]\s+/, '');
    const fileMatch = bullet.match(/(?:filePath|file):\s*`?([^`\s,|]+)`?/i);
    const specMatch = bullet.match(/(?:changeSpec|spec|action):\s*(.+)$/i);
    const symbolMatch = bullet.match(/(?:symbolOrLines|lines|symbol):\s*`?([^`|]+)`?/i);
    if (fileMatch && specMatch) {
      directives.push({
        filePath: fileMatch[1].trim(),
        symbolOrLines: symbolMatch ? symbolMatch[1].trim() : undefined,
        changeSpec: specMatch[1].trim(),
      });
    }
  }
  return directives;
}

/**
 * Formats FileEditDirective[] into a canonical JSON manifest.
 */
export function formatFileEditDirectives(directives: FileEditDirective[]): string {
  return JSON.stringify(directives, null, 2);
}


const SUPPORTED_MULTIMODAL_MIMES = new Set<string>([
  'image/png',
  'image/jpeg',
  'image/webp',
  'video/mp4',
  'application/pdf',
]);

/**
 * Converts a `MultimodalAttachment` into a native Vertex AI / Gemini `part`
 * (`fileData` when `gcs_uri` starts with `gs://`, or `inlineData` with base64).
 */
export function attachmentToGeminiPart(attachment: MultimodalAttachment): GeminiPartLike | null {
  const mimeType = (attachment.type || 'image/png').toLowerCase();
  const normalizedMime = SUPPORTED_MULTIMODAL_MIMES.has(mimeType) ? mimeType : 'image/png';

  // 1. Prefer native GCS URI (`gs://...`) for Vertex AI
  if (attachment.gcs_uri && attachment.gcs_uri.startsWith('gs://')) {
    return {
      fileData: {
        mimeType: normalizedMime,
        fileUri: attachment.gcs_uri,
      },
    };
  }

  // 2. Inline base64 data (strip `data:<mime>;base64,` prefix if present)
  const rawBase64 = attachment.base64Data || attachment.base64_data;
  if (rawBase64) {
    const cleanBase64 = rawBase64.includes('base64,')
      ? rawBase64.split('base64,')[1]
      : rawBase64;
    return {
      inlineData: {
        mimeType: normalizedMime,
        data: cleanBase64,
      },
    };
  }

  // 3. Local file fallback if `local_path` exists on disk
  if (attachment.local_path && fs.existsSync(attachment.local_path)) {
    const bytes = fs.readFileSync(attachment.local_path);
    return {
      inlineData: {
        mimeType: normalizedMime,
        data: bytes.toString('base64'),
      },
    };
  }

  // 4. Check `.state/media/<filename>` if `filename` or `/media/` public URL is provided
  const candidateName =
    attachment.filename ||
    (attachment.public_url?.includes('/media/')
      ? attachment.public_url.split('/media/').pop()
      : undefined);

  if (candidateName) {
    const safeName = path.basename(candidateName);
    const stateMediaPath = path.resolve(process.cwd(), '.state', 'media', safeName);
    if (fs.existsSync(stateMediaPath)) {
      const bytes = fs.readFileSync(stateMediaPath);
      return {
        inlineData: {
          mimeType: normalizedMime,
          data: bytes.toString('base64'),
        },
      };
    }
  }

  return null;
}

/**
 * Deterministic 768-dimensional semantic word + character trigram feature-hashing embedding.
 * Guarantees that `pgvector` cosine similarity (`1 - (embedding <=> $1)`) works 100% offline
 * with high semantic overlap for related technical queries, identifiers, and concepts.
 */
export function computeDeterministicTrigramEmbedding(text: string): number[] {
  const DIM = 768;
  const vec = new Float64Array(DIM);
  const normalized = (text || '')
    .toLowerCase()
    .replace(/[^a-z0-9_./:-]+/g, ' ')
    .trim();

  if (!normalized) {
    vec[0] = 1.0;
    return Array.from(vec);
  }

  const tokens = normalized.split(/\s+/).filter(Boolean);

  for (let tIdx = 0; tIdx < tokens.length; tIdx++) {
    const token = tokens[tIdx];
    // Weight whole words higher
    const wordHash = crypto.createHash('md5').update(`w:${token}`).digest();
    const bucket1 = wordHash.readUInt16LE(0) % DIM;
    const sign1 = (wordHash[2] & 1) === 0 ? 1 : -1;
    const bucket2 = wordHash.readUInt16LE(4) % DIM;
    const sign2 = (wordHash[6] & 1) === 0 ? 1 : -1;

    vec[bucket1] += sign1 * 2.5;
    vec[bucket2] += sign2 * 1.5;

    // Bigram context
    if (tIdx + 1 < tokens.length) {
      const bigramHash = crypto
        .createHash('md5')
        .update(`bi:${token}_${tokens[tIdx + 1]}`)
        .digest();
      const biBucket = bigramHash.readUInt16LE(0) % DIM;
      const biSign = (bigramHash[2] & 1) === 0 ? 1 : -1;
      vec[biBucket] += biSign * 1.25;
    }

    // Character trigrams for subword/stem/identifier matching (e.g. "colyseus", "pgvector", "webxr")
    const padded = `^${token}$`;
    for (let i = 0; i <= padded.length - 3; i++) {
      const tri = padded.slice(i, i + 3);
      let h = 2166136261;
      for (let c = 0; c < tri.length; c++) {
        h ^= tri.charCodeAt(c);
        h = Math.imul(h, 16777619);
      }
      const uHash = h >>> 0;
      const triBucket = uHash % DIM;
      const triSign = (uHash & 0x10000) === 0 ? 1 : -1;
      vec[triBucket] += triSign * 0.6;
    }
  }

  // L2 Normalize to unit vector for accurate cosine similarity
  let normSq = 0;
  for (let i = 0; i < DIM; i++) {
    normSq += vec[i] * vec[i];
  }
  const norm = Math.sqrt(normSq) || 1;
  const result = new Array<number>(DIM);
  for (let i = 0; i < DIM; i++) {
    result[i] = Number((vec[i] / norm).toFixed(6));
  }
  return result;
}

/**
 * Normalizes or pads/truncates any embedding vector to exactly 768 L2-normalized floats.
 */
export function normalizeVectorTo768(rawVector: number[]): number[] {
  const DIM = 768;
  const out = new Array<number>(DIM).fill(0);
  for (let i = 0; i < Math.min(DIM, rawVector.length); i++) {
    out[i] = Number(rawVector[i]) || 0;
  }
  // If source vector was > 768 dims (e.g. 1536), fold remaining dimensions in
  if (rawVector.length > DIM) {
    for (let i = DIM; i < rawVector.length; i++) {
      out[i % DIM] += (Number(rawVector[i]) || 0) * 0.5;
    }
  }
  let normSq = 0;
  for (let i = 0; i < DIM; i++) {
    normSq += out[i] * out[i];
  }
  const norm = Math.sqrt(normSq) || 1;
  for (let i = 0; i < DIM; i++) {
    out[i] = Number((out[i] / norm).toFixed(6));
  }
  return out;
}

/**
 * Computes cosine similarity between two 768-dim vectors (`1 - cosine_distance`).
 */
export function cosineSimilarity(vecA: number[], vecB: number[]): number {
  const len = Math.min(vecA.length, vecB.length);
  if (len === 0) return 0;
  let dot = 0;
  let normA = 0;
  let normB = 0;
  for (let i = 0; i < len; i++) {
    dot += vecA[i] * vecB[i];
    normA += vecA[i] * vecA[i];
    normB += vecB[i] * vecB[i];
  }
  const denom = Math.sqrt(normA) * Math.sqrt(normB);
  return denom === 0 ? 0 : dot / denom;
}


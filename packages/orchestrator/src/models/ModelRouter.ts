        tool_calls: toolCalls,
        usage: budgetCheck.stepUsage,
        usageMetadata: {
          promptTokenCount,
          cachedContentTokenCount,
          thoughtsTokenCount,
          candidatesTokenCount,
          totalTokenCount,
        },
        duration_ms: durationMs,
        simulated: false,

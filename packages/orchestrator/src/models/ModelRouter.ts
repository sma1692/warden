  public removeCredential(id: string): boolean {
    return this.credentials.delete(id);
  }

  public listCredentials(provider?: ModelProvider): ProviderCredential[] {
    const all = Array.from(this.credentials.values());
    const filtered = provider
      ? all.filter(
          (c) =>
            this.normalizeProvider(c.provider) === this.normalizeProvider(provider) ||
            c.provider === provider
        )
      : all;
    return filtered.sort((a, b) => a.priorityOrder - b.priorityOrder);
  }

  /**
   * Returns all currently active, non-cooled-down, funded credentials for `provider`
   * ordered by `priorityOrder ASC`.
   */
  public getActiveCredentialsForProvider(provider: ModelProvider): ProviderCredential[] {
    const now = Date.now();
    return this.listCredentials(provider).filter((c) => {
      if (!c.isActive) return false;
      if (c.remainingBudgetUsd <= 0) return false;
      if (c.cooldownUntil) {
        const untilMs = new Date(c.cooldownUntil).getTime();
        if (Number.isFinite(untilMs) && untilMs > now) {
          return false;
        }
        // Cooldown expired — clear it automatically
        c.cooldownUntil = null;
        c.cooldown_until = null;
      }
      return true;
    });
  }

  public selectNextCredential(
    provider: ModelProvider,
    excludeIds?: Set<string>
  ): ProviderCredential | null {
    const candidates = this.getActiveCredentialsForProvider(provider);
    for (const c of candidates) {
      if (!excludeIds || !excludeIds.has(c.id)) {
        return c;
      }
    }
    return null;
  }

  /**
   * Places a credential on cooldown after HTTP `429` (Rate Limit), `402`/`403` (Credit Exhaustion),
   * or `5xx` error so subsequent attempts immediately rotate to the next key in the pool.
   */
  public markCredentialCooldown(
    id: string,
    statusCode: number,
    reason: string,
    customCooldownMs?: number
  ): ProviderCredential | null {
    const cred = this.credentials.get(id);
    if (!cred) return null;

    let cooldownMs = customCooldownMs ?? 60_000;
    if (statusCode === 402 || (statusCode === 403 && reason.toLowerCase().includes('quota'))) {
      // Credit / quota exhaustion: mark budget 0 and 1 hour cooldown
      cred.remainingBudgetUsd = 0;
      cred.remaining_budget_usd = 0;
      cooldownMs = customCooldownMs ?? 60 * 60_000;
    } else if (statusCode === 429) {
      cooldownMs = customCooldownMs ?? 60_000;
    } else if (statusCode >= 500) {
      cooldownMs = customCooldownMs ?? 30_000;
    }

    const untilIso = new Date(Date.now() + cooldownMs).toISOString();
    cred.cooldownUntil = untilIso;
    cred.cooldown_until = untilIso;
    cred.lastError = `HTTP ${statusCode}: ${reason}`;
    cred.totalFailovers = (cred.totalFailovers || 0) + 1;
    return cred;
  }

  public clearCredentialCooldown(id: string): ProviderCredential | null {
    const cred = this.credentials.get(id);
    if (!cred) return null;
    cred.cooldownUntil = null;
    cred.cooldown_until = null;
    cred.lastError = null;
    return cred;
  }

  public deductCredentialBudget(id: string, costUsd: number): void {
    const cred = this.credentials.get(id);
    if (!cred) return;
    cred.totalRequests = (cred.totalRequests || 0) + 1;
    if (costUsd > 0 && Number.isFinite(cred.remainingBudgetUsd)) {
      cred.remainingBudgetUsd = Number(Math.max(0, cred.remainingBudgetUsd - costUsd).toFixed(6));
      cred.remaining_budget_usd = cred.remainingBudgetUsd;
    }
  }


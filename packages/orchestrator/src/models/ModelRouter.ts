        tokens_in: promptTokenCount,
        tokens_cached: cachedContentTokenCount,
        tokens_thinking: thoughtsTokenCount,
        tokens_out: candidatesTokenCount,
        duration_ms: durationMs,
        max_tokens_per_run: req.maxTokensPerRun,
